def _auto_detail_to_js(m: ProcessedModel) -> str:
    """Generate a basic auto-generated detail entry for a model without curated data."""
    # Derive capabilities from dimension scores
    dims = [
        ('推理能力', m.reasoning, '复杂逻辑推理与问题分析'),
        ('代码生成', m.coding, '多语言编程与代码调试'),
        ('数学能力', m.math, '数学问题求解与数学建模'),
        ('多模态', m.multimodal, '图像、视频等多模态内容理解'),
        ('创意写作', m.creativeWriting, '创意内容生成与文本创作'),
        ('多语言', m.multilingual, '多语言翻译与跨语言理解'),
    ]
    capabilities = [
        {'name': name, 'level': int(score), 'description': desc}
        for name, score, desc in dims
    ]

    # Derive use cases from tags
    use_cases = ['AI 助手', '内容生成']
    for tag in m.tags:
        if tag in _USE_CASE_TEMPLATES:
            for uc in _USE_CASE_TEMPLATES[tag]:
                if uc not in use_cases:
                    use_cases.append(uc)
    use_cases = use_cases[:8]

    # Build detail dict
    detail = {
        'fullDescription': (
            f'{m.name} 是 {m.company} 开发的大语言模型，'
            f'综合能力评分 {m.overallScore}/100。'
            + (f' 上下文窗口为 {m.contextLength:,} tokens。' if m.contextLength else '')
            + (f' 发布日期：{m.releaseDate}。' if m.releaseDate else '')
        ),
        'capabilities': capabilities,
        'useCases': use_cases,
        'pricing': {
            'input': '参见官方定价',
            'output': '参见官方定价',
            'context': f'{m.contextLength // 1000}K tokens' if m.contextLength else '未知',
        },
    }
    return _detail_to_js(m.id, detail)


def _detail_to_js(model_id: str, detail: dict) -> str:
    """Convert a model detail dict to JS object literal using safe serialization."""
    lines = [f"  {_safe_js_value(model_id)}: {{"]

    lines.append(f'    fullDescription: {_safe_js_value(detail.get("fullDescription", ""))},')

    caps = detail.get('capabilities', [])
    cap_lines = ['    capabilities: [']
    for i, cap in enumerate(caps):
        comma = ',' if i < len(caps) - 1 else ''
        cap_lines.append(
            f'      {{ name: {_safe_js_value(cap["name"])}, '
            f'level: {cap["level"]}, '
            f'description: {_safe_js_value(cap["description"])} }}{comma}'
        )
    cap_lines.append('    ],')
    lines.extend(cap_lines)

    cases = detail.get('useCases', [])
    lines.append(f'    useCases: {_safe_js_array(cases)},')

    pricing = detail.get('pricing', {})
    lines.append('    pricing: {')
    lines.append(f'      input: {_safe_js_value(pricing.get("input", ""))},')
    lines.append(f'      output: {_safe_js_value(pricing.get("output", ""))},')
    lines.append(f'      context: {_safe_js_value(pricing.get("context", ""))}')
    lines.append('    }')

    lines.append('  }')
    return '\n'.join(lines)
