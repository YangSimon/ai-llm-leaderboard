    content = '// AI 大模型详细信息 (自动生成)\n'
    content += '// Generated by crawler at ' + now_iso() + '\n\n'
    content += 'export const modelDetailsData = {\n'

    entries = []
    for m in models:
        detail = get_manual_detail(m.id)
        if detail:
            entries.append(_detail_to_js(m.id, detail))
        else:
            entries.append(_auto_detail_to_js(m))

    content += ',\n'.join(entries)
    content += '\n};\n\n'
    content += (
        'export const getModelDetail = (modelId) => {\n'
        '  return modelDetailsData[modelId] || {\n'
        "    fullDescription: '暂无详细信息',\n"
        '    capabilities: [],\n'
        '    useCases: [],\n'
        '    pricing: {}\n'
        '  };\n'
        '};\n'
    )

    _atomic_write(output_path, content)
    logger.info(f"Generated {output_path} ({len(entries)} models)")


